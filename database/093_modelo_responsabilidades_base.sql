-- Modelo lógico v1 de responsabilidades.
-- Cria somente a estrutura-base; não migra dados legados.
-- Execução prevista primeiro em homologação.

USE `gmodelo_dbp`;
SET NAMES utf8mb4 COLLATE utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS `responsabilidade_modulos` (
    `CODMODULO` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `CODIGO` VARCHAR(80) NOT NULL,
    `NOME` VARCHAR(150) NOT NULL,
    `DESCRICAO` VARCHAR(500) NULL,
    `ATIVO` TINYINT(1) NOT NULL DEFAULT 1,
    `ORDEM` INT NOT NULL DEFAULT 0,
    `CRIADO_EM` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `ATUALIZADO_EM` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`CODMODULO`),
    UNIQUE KEY `UK_RESP_MODULO_CODIGO` (`CODIGO`),
    KEY `IX_RESP_MODULO_ATIVO_ORDEM` (`ATIVO`, `ORDEM`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS `responsabilidade_grupoxusuario` (
    `CODGRUPOXUSUARIO` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `CODGRUPO` BIGINT UNSIGNED NOT NULL,
    `CODUSUARIO` BIGINT UNSIGNED NOT NULL,
    `VALIDO_DE` DATE NOT NULL,
    `VALIDO_ATE` DATE NULL,
    `ATIVO` TINYINT(1) NOT NULL DEFAULT 1,
    `CRIADO_EM` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `ATUALIZADO_EM` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    `CODUSUARIOALTERACAO` BIGINT UNSIGNED NULL,
    PRIMARY KEY (`CODGRUPOXUSUARIO`),
    KEY `IX_RESP_GXU_GRUPO` (`CODGRUPO`, `ATIVO`, `VALIDO_DE`, `VALIDO_ATE`),
    KEY `IX_RESP_GXU_USUARIO` (`CODUSUARIO`, `ATIVO`, `VALIDO_DE`, `VALIDO_ATE`),
    KEY `IX_RESP_GXU_ALTERACAO` (`CODUSUARIOALTERACAO`),
    CONSTRAINT `FK_RESP_GXU_GRUPO` FOREIGN KEY (`CODGRUPO`)
        REFERENCES `grupos` (`codgrupo`),
    CONSTRAINT `FK_RESP_GXU_USUARIO` FOREIGN KEY (`CODUSUARIO`)
        REFERENCES `usuarios` (`codusuario`),
    CONSTRAINT `FK_RESP_GXU_ALTERACAO` FOREIGN KEY (`CODUSUARIOALTERACAO`)
        REFERENCES `usuarios` (`codusuario`),
    CONSTRAINT `CK_RESP_GXU_DATAS` CHECK (`VALIDO_ATE` IS NULL OR `VALIDO_ATE` >= `VALIDO_DE`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS `responsabilidade_tipos` (
    `CODTIPORESPONSABILIDADE` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `CODMODULO` BIGINT UNSIGNED NOT NULL,
    `CODIGO` VARCHAR(80) NOT NULL,
    `NOME` VARCHAR(150) NOT NULL,
    `DESCRICAO` VARCHAR(500) NULL,
    `ATIVO` TINYINT(1) NOT NULL DEFAULT 1,
    `ORDEM` INT NOT NULL DEFAULT 0,
    `CRIADO_EM` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `ATUALIZADO_EM` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`CODTIPORESPONSABILIDADE`),
    UNIQUE KEY `UK_RESP_TIPO_MODULO_CODIGO` (`CODMODULO`, `CODIGO`),
    KEY `IX_RESP_TIPO_ATIVO_ORDEM` (`CODMODULO`, `ATIVO`, `ORDEM`),
    CONSTRAINT `FK_RESP_TIPO_MODULO` FOREIGN KEY (`CODMODULO`)
        REFERENCES `responsabilidade_modulos` (`CODMODULO`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS `responsabilidade_categorias` (
    `CODCATEGORIARESPONSABILIDADE` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `CODCATEGORIAORIGEM` BIGINT NULL,
    `SCHEMAORIGEM` VARCHAR(128) NULL,
    `CODIGO` VARCHAR(80) NOT NULL,
    `NOME` VARCHAR(191) NOT NULL,
    `DESCRICAO` VARCHAR(500) NULL,
    `ATIVO` TINYINT(1) NOT NULL DEFAULT 1,
    `ORDEM` INT NOT NULL DEFAULT 0,
    `SINCRONIZADO_EM` DATETIME NULL,
    `CRIADO_EM` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `ATUALIZADO_EM` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`CODCATEGORIARESPONSABILIDADE`),
    UNIQUE KEY `UK_RESP_CATEGORIA_CODIGO` (`CODIGO`),
    UNIQUE KEY `UK_RESP_CATEGORIA_ORIGEM` (`SCHEMAORIGEM`, `CODCATEGORIAORIGEM`),
    KEY `IX_RESP_CATEGORIA_ATIVO_ORDEM` (`ATIVO`, `ORDEM`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS `responsabilidade_atribuicoes` (
    `CODATRIBUICAO` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `CODMODULO` BIGINT UNSIGNED NOT NULL,
    `ORIGEM` VARCHAR(20) NOT NULL,
    `CODTIPORESPONSABILIDADE` BIGINT UNSIGNED NULL,
    `CODCATEGORIARESPONSABILIDADE` BIGINT UNSIGNED NULL,
    `ENTIDADE` VARCHAR(100) NULL,
    `REGISTRO_ID` VARCHAR(100) NULL,
    `TIPO_DESTINO` VARCHAR(10) NOT NULL,
    `CODUSUARIO` BIGINT UNSIGNED NULL,
    `CODGRUPO` BIGINT UNSIGNED NULL,
    `PRIORIDADE` INT NOT NULL DEFAULT 0,
    `PRINCIPAL` TINYINT(1) NOT NULL DEFAULT 0,
    `VALIDO_DE` DATE NOT NULL,
    `VALIDO_ATE` DATE NULL,
    `ATIVO` TINYINT(1) NOT NULL DEFAULT 1,
    `OBSERVACAO` VARCHAR(1000) NULL,
    `CRIADO_EM` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `ATUALIZADO_EM` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    `CODUSUARIOALTERACAO` BIGINT UNSIGNED NULL,
    PRIMARY KEY (`CODATRIBUICAO`),
    KEY `IX_RESP_ATRIB_MODULO` (`CODMODULO`, `ATIVO`, `VALIDO_DE`, `VALIDO_ATE`),
    KEY `IX_RESP_ATRIB_TIPO` (`CODTIPORESPONSABILIDADE`, `ATIVO`),
    KEY `IX_RESP_ATRIB_CATEGORIA` (`CODCATEGORIARESPONSABILIDADE`, `ATIVO`),
    KEY `IX_RESP_ATRIB_REGISTRO` (`CODMODULO`, `ENTIDADE`, `REGISTRO_ID`, `ATIVO`),
    KEY `IX_RESP_ATRIB_USUARIO` (`CODUSUARIO`, `ATIVO`, `VALIDO_DE`, `VALIDO_ATE`),
    KEY `IX_RESP_ATRIB_GRUPO` (`CODGRUPO`, `ATIVO`, `VALIDO_DE`, `VALIDO_ATE`),
    KEY `IX_RESP_ATRIB_ALTERACAO` (`CODUSUARIOALTERACAO`),
    CONSTRAINT `FK_RESP_ATRIB_MODULO` FOREIGN KEY (`CODMODULO`)
        REFERENCES `responsabilidade_modulos` (`CODMODULO`),
    CONSTRAINT `FK_RESP_ATRIB_TIPO` FOREIGN KEY (`CODTIPORESPONSABILIDADE`)
        REFERENCES `responsabilidade_tipos` (`CODTIPORESPONSABILIDADE`),
    CONSTRAINT `FK_RESP_ATRIB_CATEGORIA` FOREIGN KEY (`CODCATEGORIARESPONSABILIDADE`)
        REFERENCES `responsabilidade_categorias` (`CODCATEGORIARESPONSABILIDADE`),
    CONSTRAINT `FK_RESP_ATRIB_USUARIO` FOREIGN KEY (`CODUSUARIO`)
        REFERENCES `usuarios` (`codusuario`),
    CONSTRAINT `FK_RESP_ATRIB_GRUPO` FOREIGN KEY (`CODGRUPO`)
        REFERENCES `grupos` (`codgrupo`),
    CONSTRAINT `FK_RESP_ATRIB_ALTERACAO` FOREIGN KEY (`CODUSUARIOALTERACAO`)
        REFERENCES `usuarios` (`codusuario`),
    CONSTRAINT `CK_RESP_ATRIB_ORIGEM` CHECK (`ORIGEM` IN ('DIRETA', 'TIPO', 'CATEGORIA', 'GRUPO_PADRAO')),
    CONSTRAINT `CK_RESP_ATRIB_DESTINO` CHECK (`TIPO_DESTINO` IN ('USUARIO', 'GRUPO')),
    CONSTRAINT `CK_RESP_ATRIB_UM_DESTINO` CHECK (
        (`TIPO_DESTINO` = 'USUARIO' AND `CODUSUARIO` IS NOT NULL AND `CODGRUPO` IS NULL)
        OR (`TIPO_DESTINO` = 'GRUPO' AND `CODUSUARIO` IS NULL AND `CODGRUPO` IS NOT NULL)
    ),
    CONSTRAINT `CK_RESP_ATRIB_ORIGEM_REF` CHECK (
        (`ORIGEM` = 'TIPO' AND `CODTIPORESPONSABILIDADE` IS NOT NULL AND `CODCATEGORIARESPONSABILIDADE` IS NULL)
        OR (`ORIGEM` = 'CATEGORIA' AND `CODTIPORESPONSABILIDADE` IS NULL AND `CODCATEGORIARESPONSABILIDADE` IS NOT NULL)
        OR (`ORIGEM` = 'DIRETA' AND NOT (`CODTIPORESPONSABILIDADE` IS NOT NULL AND `CODCATEGORIARESPONSABILIDADE` IS NOT NULL))
        OR (`ORIGEM` = 'GRUPO_PADRAO' AND `CODTIPORESPONSABILIDADE` IS NULL AND `CODCATEGORIARESPONSABILIDADE` IS NULL)
    ),
    CONSTRAINT `CK_RESP_ATRIB_DATAS` CHECK (`VALIDO_ATE` IS NULL OR `VALIDO_ATE` >= `VALIDO_DE`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS `responsabilidade_delegacoes` (
    `CODDELEGACAO` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `CODATRIBUICAOORIGEM` BIGINT UNSIGNED NULL,
    `CODMODULO` BIGINT UNSIGNED NOT NULL,
    `ENTIDADE` VARCHAR(100) NULL,
    `REGISTRO_ID` VARCHAR(100) NULL,
    `TIPO_DESTINO` VARCHAR(10) NOT NULL,
    `CODUSUARIO` BIGINT UNSIGNED NULL,
    `CODGRUPO` BIGINT UNSIGNED NULL,
    `VALIDO_DE` DATE NOT NULL,
    `VALIDO_ATE` DATE NULL,
    `STATUS` VARCHAR(16) NOT NULL DEFAULT 'PENDENTE',
    `MOTIVO` VARCHAR(1000) NOT NULL,
    `CODUSUARIOSOLICITANTE` BIGINT UNSIGNED NOT NULL,
    `CODUSUARIOAPROVADOR` BIGINT UNSIGNED NULL,
    `CRIADO_EM` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `ATUALIZADO_EM` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    `REVOGADO_EM` DATETIME NULL,
    PRIMARY KEY (`CODDELEGACAO`),
    KEY `IX_RESP_DEL_MODULO` (`CODMODULO`, `STATUS`, `VALIDO_DE`, `VALIDO_ATE`),
    KEY `IX_RESP_DEL_ORIGEM` (`CODATRIBUICAOORIGEM`),
    KEY `IX_RESP_DEL_REGISTRO` (`CODMODULO`, `ENTIDADE`, `REGISTRO_ID`, `STATUS`),
    KEY `IX_RESP_DEL_USUARIO` (`CODUSUARIO`, `STATUS`),
    KEY `IX_RESP_DEL_GRUPO` (`CODGRUPO`, `STATUS`),
    KEY `IX_RESP_DEL_SOLICITANTE` (`CODUSUARIOSOLICITANTE`),
    KEY `IX_RESP_DEL_APROVADOR` (`CODUSUARIOAPROVADOR`),
    CONSTRAINT `FK_RESP_DEL_ORIGEM` FOREIGN KEY (`CODATRIBUICAOORIGEM`)
        REFERENCES `responsabilidade_atribuicoes` (`CODATRIBUICAO`),
    CONSTRAINT `FK_RESP_DEL_MODULO` FOREIGN KEY (`CODMODULO`)
        REFERENCES `responsabilidade_modulos` (`CODMODULO`),
    CONSTRAINT `FK_RESP_DEL_USUARIO` FOREIGN KEY (`CODUSUARIO`)
        REFERENCES `usuarios` (`codusuario`),
    CONSTRAINT `FK_RESP_DEL_GRUPO` FOREIGN KEY (`CODGRUPO`)
        REFERENCES `grupos` (`codgrupo`),
    CONSTRAINT `FK_RESP_DEL_SOLICITANTE` FOREIGN KEY (`CODUSUARIOSOLICITANTE`)
        REFERENCES `usuarios` (`codusuario`),
    CONSTRAINT `FK_RESP_DEL_APROVADOR` FOREIGN KEY (`CODUSUARIOAPROVADOR`)
        REFERENCES `usuarios` (`codusuario`),
    CONSTRAINT `CK_RESP_DEL_STATUS` CHECK (`STATUS` IN ('PENDENTE', 'ATIVA', 'REVOGADA', 'EXPIRADA', 'CANCELADA')),
    CONSTRAINT `CK_RESP_DEL_DESTINO` CHECK (`TIPO_DESTINO` IN ('USUARIO', 'GRUPO')),
    CONSTRAINT `CK_RESP_DEL_UM_DESTINO` CHECK (
        (`TIPO_DESTINO` = 'USUARIO' AND `CODUSUARIO` IS NOT NULL AND `CODGRUPO` IS NULL)
        OR (`TIPO_DESTINO` = 'GRUPO' AND `CODUSUARIO` IS NULL AND `CODGRUPO` IS NOT NULL)
    ),
    CONSTRAINT `CK_RESP_DEL_DATAS` CHECK (`VALIDO_ATE` IS NULL OR `VALIDO_ATE` >= `VALIDO_DE`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

