USE `gmodelo_dbp`;
SET NAMES utf8mb4 COLLATE utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS `legislacaoxtreinamentos` (
    `CODRELACAOTREINAMENTO` INT NOT NULL AUTO_INCREMENT,
    `CODLEGISLACAO` INT NOT NULL,
    `CODUNIDADE` INT NOT NULL DEFAULT 0,
    `CODTREINAMENTO` INT NOT NULL,
    PRIMARY KEY (`CODRELACAOTREINAMENTO`),
    UNIQUE KEY `uq_leg_treinamento_unidade` (`CODLEGISLACAO`,`CODUNIDADE`,`CODTREINAMENTO`),
    KEY `ix_leg_treinamento_legislacao` (`CODLEGISLACAO`,`CODUNIDADE`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS `legislacaoxinfraestruturas` (
    `CODRELACAOINFRAESTRUTURA` INT NOT NULL AUTO_INCREMENT,
    `CODLEGISLACAO` INT NOT NULL,
    `CODUNIDADE` INT NOT NULL DEFAULT 0,
    `CODINFRAESTRUTURA` INT NOT NULL,
    PRIMARY KEY (`CODRELACAOINFRAESTRUTURA`),
    UNIQUE KEY `uq_leg_infraestrutura_unidade` (`CODLEGISLACAO`,`CODUNIDADE`,`CODINFRAESTRUTURA`),
    KEY `ix_leg_infraestrutura_legislacao` (`CODLEGISLACAO`,`CODUNIDADE`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE OR REPLACE VIEW `vw_modulolegal_requisitos_treinamentos_grid` AS
SELECT r.`CODRELACAOTREINAMENTO`, r.`CODLEGISLACAO`, r.`CODUNIDADE`, r.`CODTREINAMENTO`, t.`DSCTREINAMENTO`
FROM `legislacaoxtreinamentos` r INNER JOIN `ml_treinamenos` t ON t.`codtreinamento`=r.`CODTREINAMENTO`;

CREATE OR REPLACE VIEW `vw_modulolegal_requisitos_infraestrutura_grid` AS
SELECT r.`CODRELACAOINFRAESTRUTURA`, r.`CODLEGISLACAO`, r.`CODUNIDADE`, r.`CODINFRAESTRUTURA`, i.`DSCINFRAESTRUTURA`
FROM `legislacaoxinfraestruturas` r INNER JOIN `ml_infraestrutura` i ON i.`codinfraestrutura`=r.`CODINFRAESTRUTURA`;
