-- P1 Green Responsibility: substituições formais e auditoria de solicitações.
SET NAMES utf8mb4 COLLATE utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS `responsabilidade_substituicoes` (
    `CODSUBSTITUICAO` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `CODATRIBUICAO` BIGINT UNSIGNED NOT NULL,
    `CODMODULO` BIGINT UNSIGNED NOT NULL,
    `TIPO_DESTINO` VARCHAR(10) NOT NULL,
    `CODUSUARIO` BIGINT UNSIGNED NULL,
    `CODGRUPO` BIGINT UNSIGNED NULL,
    `VALIDO_DE` DATE NOT NULL,
    `VALIDO_ATE` DATE NULL,
    `STATUS` VARCHAR(16) NOT NULL DEFAULT 'PENDENTE',
    `MOTIVO` VARCHAR(1000) NOT NULL,
    `CODUSUARIOSOLICITANTE` BIGINT UNSIGNED NOT NULL,
    `CODUSUARIOAPROVADOR` BIGINT UNSIGNED NULL,
    `CRIADO_EM` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `ATUALIZADO_EM` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    `REVOGADO_EM` DATETIME NULL,
    PRIMARY KEY (`CODSUBSTITUICAO`),
    KEY `IX_RESP_SUB_ATRIBUICAO` (`CODATRIBUICAO`,`STATUS`),
    KEY `IX_RESP_SUB_DESTINO` (`CODUSUARIO`,`CODGRUPO`,`STATUS`),
    KEY `IX_RESP_SUB_VIGENCIA` (`VALIDO_DE`,`VALIDO_ATE`,`STATUS`),
    CONSTRAINT `FK_RESP_SUB_ATRIBUICAO` FOREIGN KEY (`CODATRIBUICAO`) REFERENCES `responsabilidade_atribuicoes` (`CODATRIBUICAO`),
    CONSTRAINT `FK_RESP_SUB_MODULO` FOREIGN KEY (`CODMODULO`) REFERENCES `responsabilidade_modulos` (`CODMODULO`),
    CONSTRAINT `FK_RESP_SUB_USUARIO` FOREIGN KEY (`CODUSUARIO`) REFERENCES `usuarios` (`codusuario`),
    CONSTRAINT `FK_RESP_SUB_GRUPO` FOREIGN KEY (`CODGRUPO`) REFERENCES `grupos` (`codgrupo`),
    CONSTRAINT `FK_RESP_SUB_SOLICITANTE` FOREIGN KEY (`CODUSUARIOSOLICITANTE`) REFERENCES `usuarios` (`codusuario`),
    CONSTRAINT `FK_RESP_SUB_APROVADOR` FOREIGN KEY (`CODUSUARIOAPROVADOR`) REFERENCES `usuarios` (`codusuario`),
    CONSTRAINT `CK_RESP_SUB_STATUS` CHECK (`STATUS` IN ('PENDENTE','ATIVA','REVOGADA','EXPIRADA','CANCELADA')),
    CONSTRAINT `CK_RESP_SUB_DESTINO` CHECK ((`TIPO_DESTINO`='USUARIO' AND `CODUSUARIO` IS NOT NULL AND `CODGRUPO` IS NULL) OR (`TIPO_DESTINO`='GRUPO' AND `CODUSUARIO` IS NULL AND `CODGRUPO` IS NOT NULL)),
    CONSTRAINT `CK_RESP_SUB_DATAS` CHECK (`VALIDO_ATE` IS NULL OR `VALIDO_ATE` >= `VALIDO_DE`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

