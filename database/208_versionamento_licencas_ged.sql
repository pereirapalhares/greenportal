-- GreenSolutions 4.0.1 - versionamento de licencas sem tabela filha.
-- A execucao idempotente e a normalizacao fisica dos arquivos sao feitas por
-- scripts/aplicar-migracao-208-versionamento-licencas.php.
-- Caminho canonico dos arquivos:
-- E:/projetoGreen/GED/green_<empresa>/licencas/<codlicenca>/<arquivo>

ALTER TABLE li_licencas
    ADD COLUMN CODLICENCA_BASE INT NULL,
    ADD COLUMN VERSAO VARCHAR(20) NOT NULL DEFAULT '1.0',
    ADD COLUMN STATUS_VERSAO VARCHAR(30) NOT NULL DEFAULT 'ATIVA',
    ADD COLUMN CODLICENCA_ANTERIOR INT NULL,
    ADD COLUMN NOME_ARQUIVO VARCHAR(255) NULL,
    ADD COLUMN CAMINHO_ARQUIVO VARCHAR(1000) NULL,
    ADD COLUMN MIME_ARQUIVO VARCHAR(150) NULL,
    ADD COLUMN HASH_ARQUIVO CHAR(64) NULL,
    ADD COLUMN DATA_UPLOAD DATETIME NULL,
    ADD COLUMN CODUSUARIO_UPLOAD INT NULL,
    ADD COLUMN STATUS_EXTRACAO VARCHAR(30) NOT NULL DEFAULT 'NAO_SOLICITADA',
    ADD COLUMN FONTE_EXTRACAO VARCHAR(30) NULL,
    ADD COLUMN CONFIANCA_EXTRACAO DECIMAL(5,2) NULL,
    ADD COLUMN DATA_EXTRACAO DATETIME NULL,
    ADD COLUMN DADOS_EXTRACAO_JSON JSON NULL;

CREATE INDEX ix_li_licencas_versao ON li_licencas (CODLICENCA_BASE, STATUS_VERSAO, VERSAO);
CREATE INDEX ix_li_licencas_hash ON li_licencas (HASH_ARQUIVO);
