/* Fase 3 - separa o tipo documental da licença física. */
SET NAMES utf8mb4 COLLATE utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS `li_tipos_documentos` (
    `CODTIPODOCUMENTO` INT NOT NULL AUTO_INCREMENT,
    `DSCTIPODOCUMENTO` VARCHAR(255) NOT NULL,
    `ATIVO` TINYINT(1) NOT NULL DEFAULT 1,
    `ORDEM` INT NOT NULL DEFAULT 0,
    `CODUSUARIO` INT NULL,
    `CRIADO_EM` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `ATUALIZADO_EM` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`CODTIPODOCUMENTO`),
    UNIQUE KEY `uk_li_tipo_documento_nome` (`DSCTIPODOCUMENTO`),
    KEY `ix_li_tipo_documento_ativo_ordem` (`ATIVO`,`ORDEM`,`DSCTIPODOCUMENTO`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
